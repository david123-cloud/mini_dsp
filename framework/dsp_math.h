#ifndef MINI_DSP_MATH_H
#define MINI_DSP_MATH_H

/*
 * Explicit pi constant.
 *
 * M_PI is a POSIX/implementation extension, not ISO C11 (it is hidden under
 * -std=c11 -pedantic), so mini_dsp spells the value out instead.
 */
#define DSP_PI 3.14159265358979323846
#define DSP_PI_F 3.14159265358979323846f

#endif /* MINI_DSP_MATH_H */
